    @property
    def operators(self) -> typing.List[Operator]:
        """Return all operators in the library."""
        return self._operators

    @property
    def operator_names(self) -> typing.List[str]:
        """Return a list of all operator names."""
        return [op.name for op in self._operators]

    def get_by_category(self, category: str) -> typing.List[Operator]:
        """Return operators belonging to a specific category."""
        return [op for op in self._operators if op.category == category]

    def get_by_name(self, name: str) -> typing.Optional[Operator]:
        """Return an operator by its exact name."""
        for op in self._operators:
            if op.name == name:
                return op
        return None

    def format_for_llm(self) -> str:
        """Format the entire operator library as a prompt string for the LLM."""
        lines = [
            "=== OPERATOR LIBRARY (60+ Operators) ===",
            "",
            "You may ONLY use the following operators and raw fields to construct formulaic alpha factors.",
            "Each factor must be a valid, nested expression using these operators.",
            "All formulas are compiled into deterministic pandas/numpy code — precise arithmetic is guaranteed.",
            "",
        ]
        categories = {}
        for op in self._operators:
            categories.setdefault(op.category, []).append(op)

        for cat in sorted(categories.keys()):
            lines.append(f"--- {cat} ---")
            for op in categories[cat]:
                lines.append(f"  {op.signature}: {op.description}")
                if op.example:
                    lines.append(f"    Example: {op.example}")
            lines.append("")

        lines.append("=== END OF OPERATOR LIBRARY ===")
        return "\n".join(lines)

    def __len__(self) -> int:
        return len(self._operators)


