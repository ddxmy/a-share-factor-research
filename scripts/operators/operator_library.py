"""Operator Library: curated financial operators for alpha construction.

This module defines the symbolic operator set Omega used to construct
formulaic alpha factors. Each operator is a building block that transforms
market data into predictive signals.

All operators below are backed by deterministic pandas/numpy implementations
in `evaluation/evaluator.py::FormulaExecutor`, ensuring that every factor
generated by the LLM can be compiled into rigorous, hallucination-free
vectorised arithmetic.
"""

import dataclasses
import typing


